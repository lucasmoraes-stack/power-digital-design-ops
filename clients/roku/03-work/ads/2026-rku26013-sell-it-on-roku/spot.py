"""RKU26013 CTV spot: one static room for the whole spot (Lucas, 2026-10-12: no jumps or framing
breaks between storyboard frames; only the props on the table and the TV ad change).

Base room: img/raw/spot-plate-base.png (Figma AI, empty coffee table and armchair, TV off,
blown-out glass). Props: one prop group per industry generated by Figma AI (gpt-image) on flat
chroma green at the room's light and a low camera angle (img/raw/props/<ind>.png), keyed by
chroma.py (ratio key + despill, the generated contact shadows kept as a multiply), scaled and set
on the base table with a little contact occlusion. -> img/raw/spot-plate-<ind>.png, which
storyboard.py feeds to split.py.
v1 (props cut out of the industry plates) looked amateur and was dropped: _v1-wallpaper/spot-cutout-v1.py

    python -I spot.py            -> all industries + img/review/spot-props.jpg
"""
import sys
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from chroma import aikey, key, trim  # noqa: E402

RAW = HERE / "img" / "raw"
BASE = RAW / "spot-plate-base.png"

# industry: (width of the group on the 1024 base plate, bottom-centre anchor on the table top)
# table top: ellipse about x 30-630, back edge y 690, front edge y 805 at the centre
PLACE = {
    "pet":      (300, (330, 786)),
    "beauty":   (300, (330, 790)),
    "food":     (320, (330, 798)),
    "wellness": (330, (330, 792)),
    "tech":     (260, (330, 796)),
    "home":     (330, (330, 790)),
}
KEEP = {"home": 1.6}
WHITE = {"pet", "beauty", "food", "wellness", "tech", "home"}  # shot on white (green bounce was unfixable on these)  # the lilac leaves are really green
# per-object rescale inside a group: (connected component picked by its order left->right, factor)
# Lucas 2026-10-13: the beauty candle read far too big next to the bottles
PARTS = {"beauty": [(-1, 0.80)]}
GROUP = {"beauty": 0.86}  # whole group a touch smaller (the tray read ~28 cm on a ~1 m table)

# shadows (Lucas 2026-10-13: the old halo hugged every edge, even leaves in the air, and looked amateur).
# Built only from where the objects actually touch the table, with the light behind them (the window):
#   contact = thin dark line right at the foot, ao = soft pool around the base,
#   cast = the silhouette folded down onto the table (squashed by the table's perspective) and blurred
K_CAST = 0.22         # cast length per unit of object height (back light, low table perspective)
TINT = np.array([0.50, 0.56, 0.64], np.float32)   # darkening per channel: warm, saturated wood shade


def rs(img, f):
    """cv2.resize for any channel count (cv2 stops at 4)."""
    return np.dstack([cv2.resize(np.ascontiguousarray(img[..., i]), None, fx=f, fy=f, interpolation=cv2.INTER_AREA)
                      for i in range(img.shape[2])])


def rescale_parts(rgba, parts):
    """Rescale single objects of a cut-out about their bottom-centre (same foot line)."""
    a = rgba[..., 3]
    n, cc, st, _ = cv2.connectedComponentsWithStats((a > 0.05).astype(np.uint8))
    big = sorted([i for i in range(1, n) if st[i, cv2.CC_STAT_AREA] > 400], key=lambda i: st[i, cv2.CC_STAT_LEFT])
    out = rgba.copy()
    for pick, f in parts:
        i = big[pick]
        x, y, w, h = st[i, :4]
        m = (cc == i)
        piece = rgba[y:y + h, x:x + w] * m[y:y + h, x:x + w, None]
        out[y:y + h, x:x + w] *= (1 - m[y:y + h, x:x + w, None])
        piece = rs(piece, f)
        ph, pw = piece.shape[:2]
        # keep the foot line and pull it toward the group (the gap closes a little)
        nx = x + w - pw - int((w - pw) * 0.35) if pick == -1 else x + int((w - pw) * 0.35)
        ny = y + h - ph
        reg = out[ny:ny + ph, nx:nx + pw]
        reg[:] = piece + reg * (1 - piece[..., 3:4])  # 5th channel (contact) composites the same way
    return out


def contact_map(src, a):
    """Where the objects touch the table, read from the generated photo itself: the white backdrop
    right under a grounded edge is darkened by its contact shadow, under a hanging leaf or handle it
    stays white. Every lower edge counts (a tablet edge above a watch strap too), valued 0-1."""
    img = np.asarray(Image.open(src).convert("L")).astype(np.float32)
    ref = np.percentile(img[a < 0.01], 90)
    solid = a > 0.5
    h = a.shape[0]
    edge = solid & ~np.roll(solid, -1, 0)
    edge[-8:] = False
    # backdrop 3-7 px under the edge (only where it is backdrop)
    under = np.zeros_like(a); n = np.zeros_like(a)
    for k in range(3, 8):
        bg = ~np.roll(solid, -k, 0)
        under += np.roll(img, -k, 0) * bg; n += bg
    d = 1 - under / np.maximum(n, 1) / ref
    return np.where(edge & (n >= 3), np.clip((d - 0.18) / 0.25, 0, 1), 0).astype(np.float32)


def shadows(a, c, f_area):
    """Shadow darkness map for a cut-out a with contact map c (same size), light from behind."""
    h, w = a.shape
    c = np.clip(c / max(f_area, 1e-3), 0, 1)       # the one-row contact got averaged down by the resize
    c = np.where(cv2.dilate(c, np.ones((3, 1), np.uint8)) == c, c, 0)   # one peak row per edge
    c[c < 0.08] = 0
    foot = cv2.dilate(c, np.ones((3, 1), np.uint8))
    contact = np.clip(cv2.GaussianBlur(foot, (0, 0), sigmaX=1.4, sigmaY=0.8) * 2.4, 0, 1)
    # ambient pool: the foot spread wide, mostly toward the camera
    pool = np.clip(cv2.GaussianBlur(np.roll(foot, 3, 0), (0, 0), sigmaX=9, sigmaY=4) * 3.2, 0, 1)
    # ground row for every pixel: the first contact at or below it in its column; columns with no
    # contact (leaves sticking out) borrow the neighbours' ground
    G = np.full((h, w), -1.0, np.float32)
    for x in range(w):
        rows = np.where(c[:, x] > 0)[0]
        if len(rows):
            idx = np.searchsorted(rows, np.arange(h))
            G[:, x] = np.where(idx < len(rows), rows[np.minimum(idx, len(rows) - 1)], rows[-1])
    lowest = G.max(0)
    have = np.where(lowest >= 0)[0]
    if len(have):
        fill = np.interp(np.arange(w), have, lowest[have]).astype(np.float32)
        G = np.where(G < 0, fill[None, :], G)
    # cast: fold every object pixel down from its ground row, squashed
    ys, xs = np.where(a > 0.05)
    gp = G[ys, xs]
    hgt = np.maximum(gp - ys, 0)
    yp = np.clip(np.round(gp + K_CAST * hgt).astype(int), 0, h - 1)
    near = np.zeros_like(a); far = np.zeros_like(a)
    lo = hgt < max(hgt.max() * 0.3, 1) if len(hgt) else hgt > 0
    np.maximum.at(near, (yp[lo], xs[lo]), a[ys[lo], xs[lo]])
    np.maximum.at(far, (yp, xs), a[ys, xs])
    near = cv2.GaussianBlur(cv2.dilate(near, np.ones((3, 1), np.uint8)), (0, 0), sigmaX=4, sigmaY=2.5)
    far = cv2.GaussianBlur(cv2.dilate(far, np.ones((3, 1), np.uint8)), (0, 0), sigmaX=14, sigmaY=7)
    cast = np.clip(near * 0.65 + far * 0.5, 0, 1)
    dark = np.maximum(contact * 0.72, pool * 0.36 + cast * 0.36)
    return np.clip(dark, 0, 0.75)


def build(ind):
    base = np.asarray(Image.open(BASE).convert("RGB")).astype(np.float32) / 255
    src = RAW / "props" / f"{ind}.png"
    rgba, sh = aikey(src) if ind in WHITE else key(src, keep=KEEP.get(ind, 1.0))
    # the contact map rides along as a 5th channel through trim, part rescale and resize
    rgba, _ = trim(np.dstack([rgba, contact_map(src, rgba[..., 3])]), sh)
    if ind in PARTS:
        rgba = rescale_parts(rgba, PARTS[ind])
        rgba, _ = trim(rgba, np.zeros(rgba.shape[:2], np.float32))
    width, (ax, ay) = PLACE[ind]
    width = round(width * GROUP.get(ind, 1.0))
    s = width / rgba.shape[1]
    rgba = rs(rgba.astype(np.float32), s)
    # choke the matte a hair: the white backdrop survived as a pale rim on the lowest edge pixels
    a = rgba[..., 3]
    a = np.clip((a - 0.12) / 0.8, 0, 1)
    rgba[..., 3] = a
    pad = 60
    rgba = np.pad(rgba, ((pad, pad), (pad, pad), (0, 0)))
    a = rgba[..., 3]
    dark = shadows(a, rgba[..., 4], min(1.0, s)) * (1 - a)
    h, w = a.shape
    x0, y0 = ax - w // 2, ay - h + pad
    reg = base[y0:y0 + h, x0:x0 + w]
    reg *= 1 - dark[..., None] * TINT
    reg[:] = reg * (1 - a[..., None]) + rgba[..., :3] * a[..., None]
    out = RAW / f"spot-plate-{ind}.png"
    Image.fromarray((base.clip(0, 1) * 255).round().astype(np.uint8)).save(out)
    return out


if __name__ == "__main__":
    inds = sys.argv[1:] or list(PLACE)
    outs = [build(i) for i in inds]
    sheet = Image.new("RGB", (1680, 1350), "white")
    for n, p in enumerate(outs):
        sheet.paste(Image.open(p).crop((40, 560, 600, 860)).resize((840, 450), Image.LANCZOS), ((n % 2) * 840, (n // 2) * 450))
    sheet.save(HERE / "img" / "review" / "spot-props.jpg", quality=92)
    print([p.name for p in outs])
